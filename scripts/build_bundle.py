"""Build the manifest-selected single-file edition without implying tool execution."""
from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path
from urllib.parse import quote, unquote, urlsplit

try:
    from .architecture import load_architecture, package_path, validate_architecture
except ImportError:
    from architecture import load_architecture, package_path, validate_architecture

ROOT = Path(__file__).resolve().parents[1]
PACKAGE_ROOT = ROOT / "skills/ariadne-skill"
BUNDLE_PATH = ROOT / "dist/ariadne-bundle.md"
FRONTMATTER = re.compile(r"\A---\n.*?\n---\n?", re.DOTALL)
FENCE = re.compile(r"^\s{0,3}(`{3,}|~{3,})")
LINK = re.compile(r"\[([^\]]+)\]\(([^)]+)\)")
SOURCE_URL = "https://github.com/xi-kari/ariadne-skill/blob/main/skills/ariadne-skill/"
PREAMBLE = """# Ariadne — Single-File Edition

<!-- generated by scripts/build_bundle.py from architecture.json; do not edit by hand -->

This edition includes the entry, shared guidance, composable paths, and contract
guides selected by the package manifest. They form one installed methodology.

Deep library references, legacy Method Record formats, JSON schemas, and
executable tools are not embedded. Follow their source links when needed and
available; identify an inaccessible dependency rather than inventing its content
or claiming to have read it. A linked tool has not run. Formal forecasts still
need a durable registration before the outcome; without that capability, deliver
conditional paths and name the missing registration. Ordinary work uses prose or
the requested artifact and does not require a legacy twenty-field record.

Host permissions and the user's existing authorization govern tool use. This
method does not generate additional authority.
"""


def _anchor(relative: str) -> str:
    return "resource-" + hashlib.sha256(relative.encode("utf-8")).hexdigest()[:12]


def _demote_headings(body: str) -> str:
    lines: list[str] = []
    fence: tuple[str, int] | None = None
    for line in body.splitlines():
        match = FENCE.match(line)
        if match:
            run = match.group(1)
            if fence is None:
                fence = (run[0], len(run))
            elif run[0] == fence[0] and len(run) >= fence[1]:
                fence = None
            lines.append(line)
        elif fence is None and line.startswith("#"):
            lines.append("#" + line)
        else:
            lines.append(line)
    return "\n".join(lines)


def _render_resource(relative: str, included: set[str], package_root: Path) -> str:
    path = package_path(package_root, relative)
    body = FRONTMATTER.sub("", path.read_text(encoding="utf-8"), count=1).strip("\n")
    body = _demote_headings(body)

    def link(match: re.Match) -> str:
        raw = match.group(2).strip().strip("<>")
        parsed = urlsplit(unquote(raw))
        if parsed.scheme or parsed.netloc:
            return match.group(0)
        target = (path.parent / parsed.path).resolve() if parsed.path else path.resolve()
        try:
            destination = target.relative_to(package_root.resolve()).as_posix()
        except ValueError:
            raise ValueError(f"bundle resource link escapes package: {relative} -> {raw}") from None
        if destination in included:
            return f"[{match.group(1)}](#{_anchor(destination)})"
        url = SOURCE_URL + quote(destination, safe="/")
        if parsed.fragment:
            url += "#" + quote(parsed.fragment, safe="-_")
        return f"[{match.group(1)}]({url})"

    rendered: list[str] = []
    fence: tuple[str, int] | None = None
    for line in body.splitlines():
        match = FENCE.match(line)
        if match:
            run = match.group(1)
            if fence is None:
                fence = (run[0], len(run))
            elif run[0] == fence[0] and len(run) >= fence[1]:
                fence = None
            rendered.append(line)
        elif fence is None:
            # Preserve inline code examples, including example Markdown links.
            chunks = re.split(r"(`+[^`]*`+)", line)
            rendered.append("".join(chunk if chunk.startswith("`") else LINK.sub(link, chunk) for chunk in chunks))
        else:
            rendered.append(line)
    return f'<a id="{_anchor(relative)}"></a>\n\n' + "\n".join(rendered) + "\n"


def build_bundle(package_root: Path = PACKAGE_ROOT) -> str:
    data = load_architecture(package_root)
    errors = validate_architecture(data, package_root)
    if errors:
        raise ValueError("cannot build an incomplete package: " + "; ".join(errors))
    included = set(data["bundle"])
    index = "\n".join(f"- [{relative}](#{_anchor(relative)})" for relative in data["bundle"])
    sections = [PREAMBLE.rstrip() + "\n\n" + index + "\n"]
    sections.extend(_render_resource(relative, included, package_root) for relative in data["bundle"])
    return "\n".join(sections)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the committed bundle differs from the declared resources")
    args = parser.parse_args()
    try:
        generated = build_bundle()
    except (OSError, ValueError) as exc:
        print(f"bundle build failed: {exc}")
        return 1
    if args.check:
        if not BUNDLE_PATH.is_file() or BUNDLE_PATH.read_text(encoding="utf-8") != generated:
            print("dist/ariadne-bundle.md is stale; run python scripts/build_bundle.py")
            return 1
        print("single-file bundle is in sync with architecture.json")
        return 0
    BUNDLE_PATH.parent.mkdir(parents=True, exist_ok=True)
    BUNDLE_PATH.write_text(generated, encoding="utf-8", newline="\n")
    print(f"wrote {BUNDLE_PATH.relative_to(ROOT)} ({len(generated.encode('utf-8'))} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

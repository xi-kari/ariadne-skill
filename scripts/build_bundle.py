"""Build the single-file bundle for hosts without Agent Skills support.

Concatenates the ten SKILL.md bodies in dependency order into
dist/ariadne-bundle.md so the whole suite can be pasted into a web chat or a
custom system prompt. The skills/ directories stay the single source of truth;
run with --check in CI to fail when the committed bundle drifts from them.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUNDLE_PATH = ROOT / "dist" / "ariadne-bundle.md"
ORDER = (
    "ariadne-skill",
    "ariadne-framing",
    "ariadne-evidence",
    "ariadne-scale",
    "ariadne-mechanism",
    "ariadne-human",
    "ariadne-dynamics",
    "ariadne-forecast",
    "ariadne-choice",
    "ariadne-audit",
)
FRONTMATTER = re.compile(r"\A---\n(.*?)\n---\n", re.DOTALL)
DESCRIPTION = re.compile(r'^description: "?(.*?)"?$', re.MULTILINE)
REFERENCE_LINK = re.compile(r"\[([^\]]+)\]\((references/[^)]+)\)")
FENCE = re.compile(r"^\s{0,3}(`{3,}|~{3,})")

PREAMBLE = """# Ariadne Single-File Bundle

<!-- generated by scripts/build_bundle.py from skills/*/SKILL.md; do not edit by hand -->

Paste-ready form of the ten-skill Ariadne suite for hosts without an Agent
Skills directory (web chat UIs, custom instructions, plain system prompts).
Reading rules for this form:

- "Run `ariadne-x`" means: apply that module's section in this document.
- Paths like `references/...` name deep-dive files in the source repository
  (https://github.com/xi-kari/ariadne-skill); they are not inlined here. Work
  from each section's own text and mark anything that would need a reference
  file as `unknown` instead of guessing its content.
- Records cannot be schema-validated in this form. Follow the manual checklist
  in the appendix and say that validation ran by checklist, not by validator.
- Where module sections disagree with a host constraint, prefer the host's
  safety and permission rules; keep `authorization_effect: none` throughout.
"""


def _demote_headings(body: str) -> str:
    lines = []
    fence: tuple[str, int] | None = None
    for line in body.splitlines():
        match = FENCE.match(line)
        if match:
            run = match.group(1)
            if fence is None:
                fence = (run[0], len(run))
            elif run[0] == fence[0] and len(run) >= fence[1]:
                fence = None
            lines.append(line)
            continue
        if fence is None and line.startswith("#"):
            lines.append("#" + line)
        else:
            lines.append(line)
    return "\n".join(lines)


def _skill_section(name: str) -> str:
    text = (ROOT / "skills" / name / "SKILL.md").read_text(encoding="utf-8")
    match = FRONTMATTER.match(text)
    if match is None:
        raise ValueError(f"missing frontmatter: {name}")
    description_match = DESCRIPTION.search(match.group(1))
    if description_match is None:
        raise ValueError(f"missing description: {name}")
    body = text[match.end():].strip("\n")
    body_lines = body.splitlines()
    if body_lines and body_lines[0].startswith("# "):
        body = "\n".join(body_lines[1:]).strip("\n")
    body = _demote_headings(body)
    body = REFERENCE_LINK.sub(r"\1 (`\2` in the source repository)", body)
    return f"## {name}\n\n> {description_match.group(1)}\n\n{body}\n"


def _field_appendix() -> str:
    text = (ROOT / "skills" / "ariadne-mechanism" / "references" / "record-fields.md").read_text(
        encoding="utf-8"
    )
    body = "\n".join(text.splitlines()[1:]).strip("\n")
    body = _demote_headings(body)
    return f"## Appendix: Method Record fields\n\n{body}\n"


def build_bundle() -> str:
    sections = [PREAMBLE.strip("\n") + "\n"]
    sections.extend(_skill_section(name) for name in ORDER)
    sections.append(_field_appendix())
    return "\n".join(sections)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail when the committed bundle differs from the generated content",
    )
    args = parser.parse_args()

    generated = build_bundle()
    if args.check:
        if not BUNDLE_PATH.is_file():
            print(f"missing committed bundle: {BUNDLE_PATH.relative_to(ROOT)}")
            return 1
        if BUNDLE_PATH.read_text(encoding="utf-8") != generated:
            print("dist/ariadne-bundle.md is stale; run python scripts/build_bundle.py")
            return 1
        print("single-file bundle is in sync with skills/")
        return 0

    BUNDLE_PATH.parent.mkdir(parents=True, exist_ok=True)
    BUNDLE_PATH.write_text(generated, encoding="utf-8", newline="\n")
    print(f"wrote {BUNDLE_PATH.relative_to(ROOT)} ({len(generated.encode('utf-8'))} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
